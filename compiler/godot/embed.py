"""Writes godot.as as C++ source, so that the compiler carries Godot's API inside it.

Usage: embed.py <godot.as> <out.cpp> [<function name>]

The function that returns the text is godot_declarations() unless another name is given.

The text is split into pieces because some C++ compilers limit the length of one string literal.
"""
import sys

PIECE = 100  # Lines per string literal.


def main(arguments):
    if len(arguments) not in (3, 4):
        sys.stderr.write(__doc__)
        return 2
    with open(arguments[1]) as file:
        lines = file.read().split("\n")
    if ")KAS3SRC" in "\n".join(lines):
        sys.stderr.write("embed.py: the text contains the raw-string delimiter\n")
        return 1
    function = arguments[3] if len(arguments) == 4 else "godot_declarations"
    out = ["// Generated by compiler/godot/embed.py from %s. Do not edit." % arguments[1].replace("\\", "/").split("/")[-1],
           '#include "builtins.h"', "", "namespace kas3 {", "", "static const char *const PIECES_OF_%s[] = {" % function]
    for start in range(0, len(lines), PIECE):
        piece = "\n".join(lines[start:start + PIECE])
        if start + PIECE < len(lines):
            piece += "\n"
        out.append('\tR"KAS3SRC(%s)KAS3SRC",' % piece)
    out += ["};", "", "std::string %s() {" % function, "\tstd::string text;",
            "\tfor (const char *piece : PIECES_OF_%s) {" % function, "\t\ttext += piece;", "\t}", "\treturn text;", "}", "",
            "} // namespace kas3", ""]
    with open(arguments[2], "w") as file:
        file.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

"""Writes, as C++ source, what the Godot extension needs to build a project's program library by itself:
the headers generated code is built against, and one word for the backend and those headers together.

Usage: embed_runtime.py <compiler dir> <out.cpp>

The headers are `runtime/kas3.h` and every header it includes, found by following the includes through the
folders generated code is built with (`runtime`, `vm`, `ir`, `src`): no list to keep. Each is written by
its file name alone, so that one folder holds them all; two of one name would be an error here.

The word (`BUILD_IDENTITY`) changes when any of those headers or any file of `backend_cpp/` does: a program
library built by an earlier extension is then not taken for this one's (godot_ext/play_cache.h).

Each text is split into pieces because some C++ compilers limit the length of one string literal.
"""
import hashlib
import os
import re
import sys

FOLDERS = ["runtime", "vm", "ir", "src"]
START = "kas3.h"
PIECE = 100  # Lines per string literal.
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.M)


def headers(root):
    """Every header kas3.h reaches, by name: {name: path}."""
    found, pending = {}, [START]
    while pending:
        name = pending.pop()
        if name in found:
            continue
        places = [os.path.join(root, folder, name) for folder in FOLDERS if os.path.exists(os.path.join(root, folder, name))]
        if not places:
            raise SystemExit("embed_runtime.py: %s is included and is in none of %s" % (name, ", ".join(FOLDERS)))
        found[name] = places[0]
        with open(places[0]) as file:
            pending += INCLUDE.findall(file.read())
    return found


def literal(text):
    if ")KAS3SRC" in text:
        raise SystemExit("embed_runtime.py: a header contains the raw-string delimiter")
    lines = text.split("\n")
    pieces = []
    for start in range(0, len(lines), PIECE):
        piece = "\n".join(lines[start:start + PIECE])
        if start + PIECE < len(lines):
            piece += "\n"
        pieces.append('R"KAS3SRC(%s)KAS3SRC"' % piece)
    return "\n\t\t".join(pieces)


def main(arguments):
    if len(arguments) != 3:
        sys.stderr.write(__doc__)
        return 2
    root = arguments[1]
    found = headers(root)
    identity = hashlib.sha256()
    out = ["// Generated by compiler/tools/embed_runtime.py. Do not edit.", '#include "play_build.h"', "", "namespace kas3 {", "namespace play {", "",
           "const RuntimeHeader RUNTIME_HEADERS[] = {"]
    for name in sorted(found):
        with open(found[name]) as file:
            text = file.read()
        identity.update(name.encode() + b"\0" + text.encode() + b"\0")
        out.append('\t{ "%s",\n\t\t%s },' % (name, literal(text)))
    backend = os.path.join(root, "backend_cpp")
    for name in sorted(os.listdir(backend)):
        if name.endswith((".cpp", ".h")):
            with open(os.path.join(backend, name), "rb") as file:
                identity.update(name.encode() + b"\0" + file.read() + b"\0")
    out += ["};", "const size_t RUNTIME_HEADER_COUNT = sizeof(RUNTIME_HEADERS) / sizeof(RUNTIME_HEADERS[0]);",
            'const char *const BUILD_IDENTITY = "%s";' % identity.hexdigest()[:32], "", "} // namespace play", "} // namespace kas3", ""]
    text = "\n".join(out)
    # Written only when it differs: what includes nothing new is not built again.
    if not os.path.exists(arguments[2]) or open(arguments[2]).read() != text:
        with open(arguments[2], "w") as file:
            file.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
